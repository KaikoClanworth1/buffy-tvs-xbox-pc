"""Prototype: make the translated code's header fit a game DLL.

  python patch_header.py <exe .map> <gen dir>

- the registers (thread-local variables that live in the exe) become macros
  that read the exe's thread-local block directly, at the offsets the exe's
  map gives;
- the exe's plain globals are imported.
"""
import re
import sys

mp, gen = sys.argv[1], sys.argv[2]
syms = {}
for line in open(mp, errors='replace'):
    m = re.match(r'\s*[0-9a-f]{4}:[0-9a-f]{8}\s+(\S+)\s+([0-9a-f]{16})\s', line)
    if m:
        syms.setdefault(m.group(1), int(m.group(2), 16))
base, end = syms['_tls_start'], syms['_tls_end']

TLS = {  # name -> (C type, is array)
    **{n: ('uint32_t', 0) for n in 'g_eax g_ecx g_edx g_esp g_ebx g_esi g_edi g_ebp g_fs_base g_seh_ebp'.split()},
    'g_fp_stack': ('double', 1), 'g_fp_top': ('int', 0), 'g_df': ('int', 0),
    'g_fp_control_word': ('uint16_t', 0), 'g_fp_cmp': ('int', 0), 'g_fp_cc': ('uint16_t', 0),
    **{'g_xmm%d' % i: ('RecompXmm', 0) for i in range(8)},
    **{'g_mm%d' % i: ('RecompMmx', 0) for i in range(8)},
}
out = ['/* generated by patch_header.py from the exe map: the exe\'s thread-local layout */',
       '#include <intrin.h>',
       '#define BTVS_TLS (*(char **)__readgsqword(0x58))   /* the exe\'s block: TLS index 0 (checked at load) */']
for n, (t, arr) in TLS.items():
    a = syms[n]
    assert base <= a < end, n
    off = a - base
    if arr:
        out.append('#define %s ((%s *)(BTVS_TLS + 0x%X))' % (n, t, off))
    else:
        out.append('#define %s (*(%s *)(BTVS_TLS + 0x%X))' % (n, t, off))
open(gen + '/btvs_game_tls.h', 'w', newline='\n').write('\n'.join(out) + '\n')

p = gen + '/recomp_types.h'
s = open(p, encoding='utf-8', errors='surrogateescape').read()
if 'btvs_game_tls.h' not in s:
    n_tls = len(re.findall(r'(?m)^extern RECOMP_TLS [^;]*;', s))
    s = re.sub(r'(?m)^extern RECOMP_TLS ([^;]*;)', r'/* in the exe: \1 */', s)
    for d in ('extern ptrdiff_t g_xbox_mem_offset;', 'extern uint32_t g_xbox_code_lo;', 'extern uint32_t g_xbox_code_hi;'):
        assert d in s, d
        s = s.replace(d, d.replace('extern ', 'extern __declspec(dllimport) '))
    s, k = re.subn(r'(?m)^extern volatile (uint\d+_t g_icall_)', r'extern __declspec(dllimport) volatile \1', s)
    assert k == 3, k
    s = s.replace('#include <stddef.h>\n', '#include <stddef.h>\n#include "btvs_game_tls.h"\n', 1)
    open(p, 'w', encoding='utf-8', errors='surrogateescape', newline='\n').write(s)
    print('patched: %d thread-local declarations, tls block %d bytes' % (n_tls, end - base))
