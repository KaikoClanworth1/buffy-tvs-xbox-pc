/* The game dir is the D:\ root: it holds Default.xbe, pak\, media\, ...
 * Defaults to the folder the .exe lives in; BTVS_GAME_DIR overrides it
 * (test runs point it at game_files\). */
static char g_game_dir[MAX_PATH];
static char g_xbe_path[MAX_PATH];
static char g_save_dir[MAX_PATH];

static void resolve_game_paths(void)
{
    char exe_dir[MAX_PATH];
    const char *env = getenv("BTVS_GAME_DIR");
    char *slash;

    GetModuleFileNameA(NULL, exe_dir, MAX_PATH);
    slash = strrchr(exe_dir, '\\');
    if (slash) *slash = '\0';
    strcpy_s(g_game_dir, MAX_PATH, (env && *env) ? env : exe_dir);
    sprintf_s(g_xbe_path, MAX_PATH, "%s\\Default.xbe", g_game_dir);
    strcpy_s(g_save_dir, MAX_PATH, btvs_save_dir());   /* <exe>\XboxData, or BTVS_SAVE_DIR */
}

